import pandas as pd, numpy as np
df = pd.read_csv("data/train.csv")
print("Shape:", df.shape)
print("Duplicates:", df.duplicated().sum())
print("Numeric cols:", df.select_dtypes('number').shape[1], "| Categorical cols:", df.select_dtypes('object').shape[1])
print("\n--- Target SalePrice ---")
print(df["SalePrice"].describe().round(1).to_string())
print("Skew:", round(df["SalePrice"].skew(), 2), "| log1p skew:", round(np.log1p(df["SalePrice"]).skew(), 2))
print("\n--- Missing values (>0) ---")
miss = df.isna().sum()
miss = miss[miss > 0].sort_values(ascending=False)
print(miss.to_string())
print("Total missing cells:", int(df.isna().sum().sum()))
print("\n--- Top correlations with SalePrice ---")
num = df.select_dtypes('number')
corr = num.corr(numeric_only=True)["SalePrice"].drop("SalePrice").sort_values(key=abs, ascending=False)
print(corr.head(12).round(3).to_string())
print("\nBottom 5:")
print(corr.tail(5).round(3).to_string())
print("\n--- High collinearity pairs (|r|>0.85) ---")
c = num.corr().abs()
pairs = []
for i in range(len(c.columns)):
    for j in range(i+1, len(c.columns)):
        if c.iloc[i, j] > 0.85:
            pairs.append((c.columns[i], c.columns[j], round(c.iloc[i, j], 3)))
for p in pairs: print(p)
print("\n--- Skewed numeric features (skew>0.75) ---")
sk = num.skew().sort_values(ascending=False)
print(sk[sk > 0.75].round(2).to_string())
print("\n--- Outlier check GrLivArea ---")
print(df.nlargest(4, "GrLivArea")[["Id", "GrLivArea", "SalePrice", "OverallQual"]].to_string(index=False))
print("\n--- Categorical unique counts (top) ---")
cat = df.select_dtypes('object')
print(cat.nunique().sort_values(ascending=False).head(10).to_string())
print("Neighborhood count:", df["Neighborhood"].nunique())
print("Neighborhood median price (top 3):")
print(df.groupby("Neighborhood")["SalePrice"].median().sort_values(ascending=False).head(3).round(0).to_string())
